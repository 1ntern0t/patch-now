// Builds docs/core.js: the pure modules in src/core/ wrapped as one classic
// script (no ES modules, so docs/index.html also works when opened from disk
// with file://). Each module keeps its own function scope. Run after editing
// src/core/; test/docs.test.js fails if the bundle is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Dependency order.
export const MODULES = ['errors', 'display', 'semver', 'debian', 'pep440', 'compare', 'inventory', 'severity', 'osv', 'kev', 'report'];

const root = new URL('../', import.meta.url);

export function buildBundle() {
  const parts = [
    '// GENERATED by scripts/build-docs.js from src/core/*.js. Do not edit by hand.',
    "'use strict';",
    'var PatchNow = (function () {'
  ];
  const all = [];
  for (const name of MODULES) {
    let src = readFileSync(new URL(`src/core/${name}.js`, root), 'utf8');
    const exports = [...src.matchAll(/^export (?:async )?(?:function|const|let|class) ([A-Za-z0-9_$]+)/gm)].map((m) => m[1]);
    src = src.replace(/^import \{([^}]+)\} from '\.\/([a-z0-9]+)\.js';$/gm, (_, names, mod) => {
      if (!MODULES.includes(mod)) throw new Error(`unknown import ${mod} in ${name}`);
      return `  const {${names}} = __${mod};`;
    });
    if (/^\s*import\s/m.test(src)) throw new Error(`unsupported import in ${name}`);
    src = src.replace(/^export /gm, '');
    parts.push(`  const __${name} = (function () {`, src, `  return { ${exports.join(', ')} };`, '  })();');
    all.push(name);
  }
  parts.push(`  return Object.freeze(Object.assign({}, ${all.map((n) => '__' + n).join(', ')}));`, '})();', '');
  return parts.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('docs/core.js', root), buildBundle());
  console.log('wrote docs/core.js');
}
